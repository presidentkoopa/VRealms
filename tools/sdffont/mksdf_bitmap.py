#!/usr/bin/env python3
"""mksdf_bitmap.py -- an SDF atlas from a BITMAP font's glyph pictures (mksdf.ps1 does the same from a TTF).

    python3 mksdf_bitmap.py <glyph dir> <out.png> <out.txt> [--name NAME]

<glyph dir> holds Doom-style SmallFont pictures, stcfnNNN.png (NNN = the character code), all drawn on one cell
height. Written for JFO's Hires/SmallFont (JDUI by Zedas, Blackmore1014 edit): 33..95, 32 px tall, capitals only.

Same output contract as mksdf.ps1, so FSDFFont reads it unchanged (hw_sdffont.h):
  - cell CELL, spread SPREAD, em = CELL - 2*SPREAD; the em box's top-left is at (spread, spread) in each cell;
  - each texel is 0.5 + distance/(2*spread), positive inside, in R=G=B, alpha 255; a glyph with no ink is all 0;
  - "g code x y w h advance", advance in cell pixels; the ink starts at the em box's left edge, and the emitter
    clips each quad to advance + 2*spread, so the ink must sit inside [spread, spread + advance).

THE SHAPE IS THE METAL, NOT THE OUTLINE. JFO's glyphs are bright metal inside a dark rim, and the picture is opaque
over both. The field is taken from the bright part: the engine tints and haloes the field itself, and a shape that
included the rim would draw every letter as a fat blob.

PLACEMENT follows RSQ_UBQSeries GunCards/tools/jfo.py: a glyph is cropped to its inked columns, keeps its row
position in the font's line height (32), a short picture ('-' is 32 x 16) is centred in the line, '.' and ',' sit on
its foot. Advance = ink width + 2 source pixels (jfo.py's proportional spacing). Lower case uses the capitals, as
Doom's SmallFont does; characters the font lacks borrow a near shape and are listed in the metrics header.
"""
import argparse, os, sys
import numpy as np
from PIL import Image
from scipy import ndimage

ap = argparse.ArgumentParser()
ap.add_argument('glyphs'); ap.add_argument('out_png'); ap.add_argument('out_txt')
ap.add_argument('--name', default='JFO SmallFont (JDUI by Zedas, Blackmore1014 edit)')
ap.add_argument('--cell', type=int, default=96); ap.add_argument('--spread', type=int, default=16)
ap.add_argument('--super', type=int, default=8); ap.add_argument('--line', type=int, default=32)
a = ap.parse_args()

CELL, SPREAD, SUP, LINE = a.cell, a.spread, a.super, a.line
EM = CELL - 2 * SPREAD
K = EM / LINE                      # cell pixels per source pixel (2 for a 32 px font in a 64 px em)
FIRST, LAST = 32, 126

def path(code): return os.path.join(a.glyphs, 'stcfn%03d.png' % code)

# Characters the font does not draw: lower case -> capitals; the rest -> the nearest shape it has.
BORROW = {96: 39, 123: 40, 124: 121, 125: 41, 126: 45}   # stcfn121 is Doom's '|', not 'y'
borrowed = []
def source_code(c):
    if c == 32: return None
    if 97 <= c <= 122: return c - 32
    if c in BORROW and os.path.exists(path(BORROW[c])): borrowed.append((c, BORROW[c])); return BORROW[c]
    if os.path.exists(path(c)): return c
    return None

def ink_mask(code):
    """the metal at SUP x cell-pixel resolution, placed in a LINE-tall row; (mask, ink width in source px)"""
    im = Image.open(path(code)).convert('RGBA')
    arr = np.asarray(im).astype(np.float32) / 255.0
    lum = (0.299 * arr[..., 0] + 0.587 * arr[..., 1] + 0.114 * arr[..., 2]) * arr[..., 3]
    # The metal has dark grain in it; thresholded raw it leaves pinholes. Close the grain and fill its pinholes (never a
    # letter's counter), at the picture's own resolution, then smooth only the outline for the upscale.
    m = ndimage.binary_closing(lum > 0.30, structure=np.ones((2, 2)), border_value=0)
    holes, nh = ndimage.label(ndimage.binary_fill_holes(m) & ~m)
    if nh:
        sizes = ndimage.sum(np.ones_like(holes), holes, range(1, nh + 1))
        for k, sz in enumerate(sizes, 1):
            if sz < 6: m |= holes == k          # grain, not a counter (O, A, 8 keep theirs)
    lum = ndimage.gaussian_filter(m.astype(np.float32), 0.5)
    cols = np.where(m.any(axis=0))[0]
    if len(cols) == 0: return None, 0
    x0, x1 = cols[0], cols[-1] + 1
    w, h = x1 - x0, im.size[1]
    row = Image.new('F', (w, LINE), 0.0)
    if h >= LINE: dy = 0
    elif code in (44, 46): dy = LINE - h
    else: dy = (LINE - h) // 2
    row.paste(Image.fromarray(lum[:min(h, LINE), x0:x1]), (0, dy))
    S = K * SUP
    big = row.resize((int(round(w * S)), int(round(LINE * S))), Image.BICUBIC)
    return np.asarray(big) > 0.5, w

cols_n = 16
count = LAST - FIRST + 1
rows_n = (count + cols_n - 1) // cols_n
AW, AH = cols_n * CELL, rows_n * CELL
atlas = np.zeros((AH, AW), np.uint8)
lines = ['# SDF font metrics -- generated by tools/sdffont/mksdf_bitmap.py, do not edit',
         'font ' + a.name, 'cell %d' % CELL, 'spread %d' % SPREAD, 'em %g' % EM, 'atlas %d %d' % (AW, AH)]
glines = []
space_adv = 0.5 * EM               # Doom's SmallFont space: half the line height
S = CELL * SUP
for i, c in enumerate(range(FIRST, LAST + 1)):
    gx, gy = (i % cols_n) * CELL, (i // cols_n) * CELL
    src = source_code(c)
    mask, w = ink_mask(src) if src is not None else (None, 0)
    if mask is None:
        glines.append('g %d %d %d %d %d %.3f' % (c, gx, gy, CELL, CELL, space_adv if c == 32 else 0.0))
        continue
    canvas = np.zeros((S, S), bool)
    ox = oy = SPREAD * SUP
    canvas[oy:oy + mask.shape[0], ox:ox + mask.shape[1]] = mask[:S - oy, :S - ox]
    inside = ndimage.distance_transform_edt(canvas)
    outside = ndimage.distance_transform_edt(~canvas)
    d = (inside - outside) / SUP                                  # signed, cell pixels
    d = d.reshape(CELL, SUP, CELL, SUP).mean(axis=(1, 3))
    n = np.clip(np.round((0.5 + d / (2.0 * SPREAD)) * 255), 0, 255).astype(np.uint8)
    atlas[gy:gy + CELL, gx:gx + CELL] = n
    glines.append('g %d %d %d %d %d %.3f' % (c, gx, gy, CELL, CELL, (w + 2) * K))
if borrowed:
    lines.append('# borrowed shapes (code<-code): ' + ' '.join('%d<-%d' % b for b in borrowed))
lines.append('# lower case drawn with the capitals (the font has none)')
open(a.out_txt, 'w').write('\n'.join(lines + glines) + '\n')
rgba = np.dstack([atlas, atlas, atlas, np.full_like(atlas, 255)])
Image.fromarray(rgba, 'RGBA').save(a.out_png)
print('wrote %s (%dx%d) and %s: %d glyphs' % (a.out_png, AW, AH, a.out_txt, count))

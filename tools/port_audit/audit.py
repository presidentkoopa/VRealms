#!/usr/bin/env python3
"""Every function of ROTH.C (the original, lifted to C) against this port.

    tools/port_audit/audit.py [ROTH.C engine dir] > docs/PORT_AUDIT.md

For each function defined in ROTH.C's src/engine/*.c: its file:line there, its original address where the comment
gives one, and where this port NAMES it (by name or by address) in src/roth, src/maploader or src/playsim -- the first
place, file:line. Named is not the same as ported: a port names a function when it ports it, and also when it says it
does not. The list is the starting point of the audit, not its verdict; the verdict per function is written by hand
into docs/PORT_GAPS.md.

Files whose job the engine (GZDoom) does in its own way -- drawing, DOS, memory, the asset archive, the video modes --
are listed separately: a function there is not expected in the port by name.
"""
import re, os, glob, sys, collections
E = sys.argv[1] if len(sys.argv) > 1 else '/home/claude/oracle_build/rothc/roth_c/src/engine'
P = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
REPLACED = {'renderer.c', 'render_world.c', 'blit_2d.c', 'video_display.c', 'dos_runtime.c', 'dpmi_dos_os.c',
            'memory_pool.c', 'das_assets.c', 'math_util.c', 'file_config.c', 'text_font.c'}
defre = re.compile(r'^(?:static\s+)?(?:inline\s+)?[A-Za-z_][\w \*]*?[\s\*]([a-z_][a-z0-9_]*)\s*\(([^;]*)$')
funcs = []
for f in sorted(glob.glob(E + '/*.c')):
    lines = open(f, errors='replace').read().split('\n')
    for i, l in enumerate(lines):
        m = defre.match(l)
        if not m: continue
        name = m.group(1)
        if name in ('if', 'for', 'while', 'switch', 'return', 'sizeof'): continue
        va = None
        for j in range(i - 1, max(0, i - 25), -1):
            mm = re.search(re.escape(name) + r'\s*\((0x[0-9a-fA-F]+)', lines[j])
            if mm: va = mm.group(1).lower(); break
        funcs.append(dict(file=os.path.basename(f), name=name, va=va, line=i + 1, static=l.startswith('static')))
port = []
for pat in ['src/roth/*.cpp', 'src/roth/*.h', 'src/maploader/*.cpp', 'src/maploader/*.h', 'src/playsim/*.cpp']:
    for f in sorted(glob.glob(os.path.join(P, pat))):
        rel = os.path.relpath(f, P)
        for n, l in enumerate(open(f, errors='replace')):
            port.append((rel, n + 1, l.lower()))
def where(fn):
    keys = [fn['name'].lower()] + ([fn['va']] if fn['va'] else [])
    for rel, n, l in port:
        for k in keys:
            if k in l and (k != fn['name'].lower() or re.search(r'\b' + re.escape(k) + r'\b', l)):
                return f'{rel}:{n}'
    return None
by = collections.defaultdict(list)
for fn in funcs: by[fn['file']].append((fn, where(fn)))
print('# ROTH.C against the port, function by function (generated by tools/port_audit/audit.py)\n')
print('Named = the port mentions the function or its address somewhere; that is where to look, not proof it is ported.\n')
print('| ROTH.C file | functions | named in the port | not named | |\n|---|---|---|---|---|')
for f in sorted(by, key=lambda k: (k in REPLACED, k)):
    n = len(by[f]); h = sum(1 for _, w in by[f] if w)
    print(f'| {f} | {n} | {h} | {n - h} | {("mostly drawing, some logic: check" if f == "renderer.c" else "the engine does this") if f in REPLACED else "game"} |')
for f in sorted(by, key=lambda k: (k in REPLACED, k)):
    print(f'\n## {f}{" (the engine does this job)" if f in REPLACED else ""}\n')
    print('| function | address | ROTH.C | named in the port at |\n|---|---|---|---|')
    for fn, w in by[f]:
        print(f'| {fn["name"]}{" (static)" if fn["static"] else ""} | {fn["va"] or ""} | {f}:{fn["line"]} | {w or "**not named**"} |')
